#!/usr/bin/env python3
"""Idempotently prepend the OCCT per-file license notice to generated OCP files.

Background (CadQuery/OCP#234): the OCP bindings (``.cpp``) and typing stubs
(``.pyi``) are generated by processing OCCT C++ headers, so each generated file
reproduces OCCT material (documentation, declarations) and, in *source* form,
falls under the GNU LGPL-2.1 directly -- the Open CASCADE Exception covers object
code only. Every distributed generated source/stub file therefore needs the OCCT
copyright + LGPL notice. The OCP generator is expected to emit it; this script is
a **safety net** run at packaging time so that, if a file ever arrives without
the notice, one is added before the file is shipped.

It is idempotent: a file that already carries an LGPL / OCCT-exception header
(whether from the generator or a previous run) is left untouched, so the notice
is never duplicated.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

# Lines of the notice (without the comment prefix). ``{occt}`` is filled in.
NOTICE = [
    "This file was generated by OCP from Open CASCADE Technology (OCCT) {occt}",
    "headers and contains material from them, including documentation.",
    "",
    "Copyright (c) OPEN CASCADE SAS and contributors",
    "",
    "This file is part of the Open CASCADE Technology software library.",
    "",
    "This library is free software; you can redistribute it and/or modify it",
    "under the terms of the GNU Lesser General Public License version 2.1 as",
    "published by the Free Software Foundation, with special exception defined",
    "in the file OCCT_LGPL_EXCEPTION.txt. Consult the file LICENSE_LGPL_21.txt",
    "included in the OCCT distribution for complete text of the license and",
    "disclaimer of any warranty.",
    "",
    "Alternatively, this file may be used under the terms of Open CASCADE",
    "commercial license or contractual agreement.",
    "",
    "(Notice added by the ocp-build-system packaging step as a safety net; see",
    "https://github.com/CadQuery/OCP/issues/234 .)",
]

# Comment prefix by file extension.
COMMENT = {
    ".pyi": "#", ".py": "#",
    ".cpp": "//", ".cxx": "//", ".cc": "//", ".c": "//",
    ".hxx": "//", ".hpp": "//", ".hh": "//", ".h": "//",
}

# A file is considered already-noticed if either phrase appears in its opening
# lines. This matches both this notice and any header the generator (or OCCT
# itself) emits using the standard LGPL + exception wording.
SENTINELS = ("GNU Lesser General Public License", "OCCT_LGPL_EXCEPTION")
SCAN_LINES = 50

CODING_RE = re.compile(r"^#.*coding[:=]")


def already_noticed(text: str) -> bool:
    head = "\n".join(text.split("\n", SCAN_LINES)[:SCAN_LINES])
    return any(s in head for s in SENTINELS)


def build_block(comment: str, occt: str) -> str:
    out = []
    for line in NOTICE:
        line = line.format(occt=occt)
        out.append((comment + " " + line).rstrip() if line else comment)
    return "\n".join(out) + "\n\n"


def insert_point(lines: list[str]) -> int:
    """Index after any shebang / coding-cookie lines, so the notice stays valid."""
    i = 0
    if lines and lines[0].startswith("#!"):
        i = 1
    if len(lines) > i and CODING_RE.match(lines[i]):
        i += 1
    return i


def add_header(path: Path, occt: str) -> bool:
    comment = COMMENT.get(path.suffix.lower())
    if comment is None:
        return False
    try:
        text = path.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError):
        return False
    if already_noticed(text):
        return False
    block = build_block(comment, occt)
    lines = text.split("\n")
    at = insert_point(lines)
    if at == 0:
        new = block + text
    else:
        new = "\n".join(lines[:at]) + "\n" + block + "\n".join(lines[at:])
    path.write_text(new, encoding="utf-8")
    return True


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", required=True, help="directory tree to process")
    ap.add_argument("--occt", required=True, help="OCCT version string, e.g. 8.0.1")
    ap.add_argument("--ext", nargs="+", default=[".pyi"],
                    help="file extensions to process (default: .pyi)")
    args = ap.parse_args()

    root = Path(args.root)
    if not root.exists():
        print(f"[license-headers] ERROR: root {root} does not exist", flush=True)
        return 2
    exts = {e if e.startswith(".") else "." + e for e in args.ext}

    scanned = added = skipped = 0
    for p in sorted(root.rglob("*")):
        if not p.is_file() or p.suffix.lower() not in exts:
            continue
        scanned += 1
        if add_header(p, args.occt):
            added += 1
        else:
            skipped += 1

    print(f"[license-headers] {root}: scanned {scanned}, added {added}, "
          f"already-present {skipped} (ext={sorted(exts)})", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
